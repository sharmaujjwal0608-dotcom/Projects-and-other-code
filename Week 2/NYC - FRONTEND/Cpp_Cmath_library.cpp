//cmath library
//include is used to use a library
#include <iostream>
using namespace std;

#include <cmath>

int main(){
    cout << max(9,10) << endl;
    cout << min(9,10) << endl;
    cout << pow(9,10) << endl;
    cout << ceil(9.5) << endl;// closest upper value
    cout << floor(9.5) << endl;// closest lower value
    cout << sqrt(9) << endl;// for square root
    


    return 0;
}